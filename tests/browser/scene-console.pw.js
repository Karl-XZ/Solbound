async page => {
  await page.route('**/*',route=>route.continue());
  await page.setViewportSize({width:1680,height:858});
  await page.reload();
  await page.evaluate(()=>{World.setMode('surface');document.querySelector('#title').classList.remove('on');World.reset();__dbg.newGame();__dbg.startGame();});
  await page.getByRole('button',{name:'开始教程',exact:true}).click();
  await page.getByRole('button',{name:'控制台：查看发电和分配电力',exact:true}).click();
  if(!await page.locator('#notebook').isHidden())throw Error('控制台仍然打开日记');
  if(!await page.locator('#habitatScene').isHidden())throw Error('控制台没有切换到 3D 全景');
  if(!await page.locator('#fieldDialog').isHidden())throw Error('控制台仍然先弹出说明');
  if(await page.locator('#notebook #power, #notebook #meters').count())throw Error('分电和资源仍然在日记内');
  if(!await page.locator('#baseConsole #power').isVisible())throw Error('底部缺少分电面板');
  const panel=await page.locator('#power').boundingBox(),meters=await page.locator('#meters').boundingBox(),weather=await page.locator('#fore').boundingBox();
  if(panel.y<515 || panel.width>800 || meters.x>60 || meters.y>180 || weather.x<1350)throw Error('未恢复截图中的左右仪表和底部能源卡');
  if(await page.locator('#meters .m-row').count()!==5)throw Error('原有五项资源仪表缺失');
  if(await page.locator('#power .slot').count()!==4)throw Error('原有四项分电缺失');
  if(await page.evaluate(()=>Expedition.model.step)!=='depart')throw Error('打开控制台未完成教程检查');
  const before=await page.evaluate(()=>({o2:__dbg.G().o2,dose:__dbg.G().dose,alloc:__dbg.G().alloc.o2}));
  await page.locator('.slot[data-k="o2"] .pl').click();
  if(await page.evaluate(()=>__dbg.G().alloc.o2)!==before.alloc+1)throw Error('分电按钮不工作');
  if(await page.evaluate(()=>Expedition.outside || __dbg.G().o2!==60 || __dbg.G().dose!==0))throw Error('打开控制台触发实际出舱');
  await page.mouse.move(700,100);
  await page.waitForTimeout(2000);
  await page.screenshot({path:'output/playwright/scene-console-desktop.png'});
  await page.locator('#evaDepart').click();
  await page.locator('#fieldDialog').getByRole('button',{name:'取消出舱'}).click();
  await page.locator('#skipGuide').click();
  await page.locator('.slot[data-k="o2"] .mn').click();
  await page.mouse.move(700,100);await page.waitForTimeout(2000);
  await page.waitForFunction(()=>!document.querySelector('#cabinToast').classList.contains('visible'));
  await page.screenshot({path:'output/playwright/scene-console-restored.png'});
  await page.locator('#bGo').click();
  if(!await page.locator('#fieldDialog .night-ledger').isVisible())throw Error('控制台不能结束当天');
  await page.locator('#fieldDialog').getByRole('button',{name:'返回控制台',exact:true}).click();
  if(!await page.locator('#notebook').isHidden() || !await page.locator('#power').isVisible())throw Error('返回控制台又打开了日记');
  await page.locator('#consoleReturn').click();
  if(!await page.locator('#habitatScene').isVisible())throw Error('控制台不能返回生活舱');
  return {console:'direct 3D',resources:'left',weather:'right',allocation:'bottom center',diary:'closed',EVA:'not charged'};
}
