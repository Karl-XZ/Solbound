async page => {
  await page.route('**/*',route=>route.continue());
  await page.setViewportSize({width:1680,height:858});
  await page.reload();
  await page.evaluate(()=>{World.setMode('surface');document.querySelector('#title').classList.remove('on');World.reset();__dbg.newGame();__dbg.startGame();});
  await page.getByRole('button',{name:'Start Tutorial',exact:true}).click();
  await page.getByRole('button',{name:'Console: check power and share it out',exact:true}).click();
  if(!await page.locator('#notebook').isHidden())throw Error('The Console still opens the log');
  if(!await page.locator('#habitatScene').isHidden())throw Error('The Console did not switch to the 3D view');
  if(!await page.locator('#fieldDialog').isHidden())throw Error('The Console still shows a notice first');
  if(await page.locator('#notebook #power, #notebook #meters').count())throw Error('Power plan and resources are still inside the log');
  if(!await page.locator('#baseConsole #power').isVisible())throw Error('The power panel is missing at the bottom');
  const panel=await page.locator('#power').boundingBox(),meters=await page.locator('#meters').boundingBox(),weather=await page.locator('#fore').boundingBox();
  if(panel.y<515 || panel.width>800 || meters.x>60 || meters.y>180 || weather.x<1350)throw Error('The left/right gauges and bottom power card are not restored');
  if(await page.locator('#meters .m-row').count()!==5)throw Error('The five resource gauges are missing');
  if(await page.locator('#power .slot').count()!==4)throw Error('The four power controls are missing');
  if(await page.evaluate(()=>Expedition.model.step)!=='depart')throw Error('Opening the Console did not complete the tutorial check');
  const before=await page.evaluate(()=>({o2:__dbg.G().o2,dose:__dbg.G().dose,alloc:__dbg.G().alloc.o2}));
  await page.locator('.slot[data-k="o2"] .pl').click();
  if(await page.evaluate(()=>__dbg.G().alloc.o2)!==before.alloc+1)throw Error('Power buttons do not work');
  if(await page.evaluate(()=>Expedition.outside || __dbg.G().o2!==60 || __dbg.G().dose!==0))throw Error('Opening the Console started a real trip outside');
  await page.mouse.move(700,100);
  await page.waitForTimeout(2000);
  await page.screenshot({path:'output/playwright/scene-console-desktop.png'});
  await page.locator('#evaDepart').click();
  await page.locator('#fieldDialog').getByRole('button',{name:'Cancel'}).click();
  await page.locator('#skipGuide').click();
  await page.locator('.slot[data-k="o2"] .mn').click();
  await page.mouse.move(700,100);await page.waitForTimeout(2000);
  await page.waitForFunction(()=>!document.querySelector('#cabinToast').classList.contains('visible'));
  await page.screenshot({path:'output/playwright/scene-console-restored.png'});
  await page.locator('#bGo').click();
  if(!await page.locator('#fieldDialog .night-ledger').isVisible())throw Error('The Console cannot end the day');
  await page.locator('#fieldDialog').getByRole('button',{name:'Back to Console',exact:true}).click();
  if(!await page.locator('#notebook').isHidden() || !await page.locator('#power').isVisible())throw Error('Going back to the Console opened the log again');
  await page.locator('#consoleReturn').click();
  if(!await page.locator('#habitatScene').isVisible())throw Error('The Console cannot go back to the habitat');
  return {console:'direct 3D',resources:'left',weather:'right',allocation:'bottom center',diary:'closed',EVA:'not charged'};
}
