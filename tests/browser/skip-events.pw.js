async page => {
  await page.route('**/*',route=>route.continue());await page.reload();
  await page.evaluate(()=>{World.setMode('surface');document.querySelector('#title').classList.remove('on');});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.evaluate(()=>{World.reset();__dbg.newGame();__dbg.startGame();});
  await page.getByRole('button',{name:'跳过教程'}).click();
  let state=await page.evaluate(()=>({water:__dbg.G().water,batt:__dbg.G().batt,damage:__dbg.G().damaged,active:Expedition.model.guide.active,tasks:Expedition.model.tasks.map(t=>t.phase)}));
  if(state.water!==55||state.batt!==6||state.damage!==1||state.active||state.tasks.some(t=>t!=='ready'))throw Error('skip entry '+JSON.stringify(state));
  await page.evaluate(()=>{World.reset();__dbg.newGame();__dbg.startGame();});
  await page.getByRole('button',{name:'开始教程'}).click();
  await page.locator('#cabinPower').click();
  await page.locator('#evaDepart').click();
  await page.locator('#fieldDialog').getByRole('button',{name:'出舱',exact:true}).click();
  await page.locator('#skipGuide').click();
  state=await page.evaluate(()=>({water:__dbg.G().water,batt:__dbg.G().batt,o2:__dbg.G().o2,active:Expedition.model.guide.active}));
  if(state.water!==55||state.batt!==6||state.o2!==57||state.active)throw Error('skip midway '+JSON.stringify(state));
  await page.locator('#nearbyAction').click();
  await page.getByRole('button',{name:'床：确认收支并结束一天'}).click();
  await page.getByRole('button',{name:'确认结束今天'}).click();
  await page.waitForFunction(()=>__dbg.G().sol===2,null,{timeout:15000});
  if(await page.evaluate(()=>Expedition.model.guide.active))throw Error('guide leaked into day two');
  await page.evaluate(()=>{World.reset();__dbg.newGame();__dbg.startGame();});
  await page.getByRole('button',{name:'跳过教程'}).click();
  await page.evaluate(()=>__dbg.openEvent('delta',()=>{}));
  const options=await page.locator('#dailyEventModal .event-option').count();
  if(options!==3)throw Error('hidden third event choice');
  const sciBefore=await page.evaluate(()=>__dbg.G().sci);
  await page.getByRole('button',{name:/亲自出舱采样/}).click();
  if(await page.evaluate(()=>__dbg.G().sample)||await page.evaluate(()=>__dbg.G().sci)!==sciBefore)throw Error('sample completed without field work');
  await page.evaluate(()=>{__dbg.G().storm=2;__dbg.renderAll();});
  await page.getByRole('button',{name:'舱门：检查装备并出舱'}).click();
  if(await page.locator('#fieldDialog .field-button').first().isEnabled())throw Error('storm permits departure');
  await page.getByRole('button',{name:'取消出舱'}).click();
  await page.evaluate(()=>{__dbg.G().storm=0;__dbg.G().evaLock=0;__dbg.renderAll();});
  await page.getByRole('button',{name:'舱门：检查装备并出舱'}).click();
  await page.getByRole('button',{name:'出舱',exact:true}).click();
  await page.keyboard.down('KeyS');await page.waitForTimeout(300);
  await page.locator('#fieldMap').click();
  const paused=await page.evaluate(()=>World.getPlayer());await page.waitForTimeout(300);
  const afterPause=await page.evaluate(()=>World.getPlayer());await page.keyboard.up('KeyS');
  if(Math.hypot(afterPause.x-paused.x,afterPause.z-paused.z)>.01)throw Error('movement continued in dialog');
  await page.getByRole('button',{name:'关闭列表'}).click();await page.waitForTimeout(200);
  const resumed=await page.evaluate(()=>World.getPlayer());
  if(Math.hypot(resumed.x-paused.x,resumed.z-paused.z)>.01)throw Error('held key resumed after pause');
  await page.locator('#fieldMap').click();await page.getByRole('button',{name:'移到舱门外'}).click();
  await page.locator('#nearbyAction').click();
  if(await page.evaluate(()=>Expedition.outside))throw Error('help return stuck');
  return {skipEntry:'pass',skipMidway:'pass',eventOptions:options,physicalChoice:'deferred',storm:'blocked',pausedInput:'cleared',errors};
}
