async page => {
  await page.route('**/*',route=>route.continue());
  await page.setViewportSize({width:1440,height:1000});
  await page.reload();
  await page.evaluate(()=>{World.setMode('surface');document.querySelector('#title').classList.remove('on');World.reset();__dbg.newGame();__dbg.startGame();});
  await page.getByRole('button',{name:'跳过教程',exact:true}).click();
  if(await page.getByRole('button',{name:'资源仪表',exact:true}).count()!==1)throw Error('原有资源仪表没有直达入口');
  await page.getByRole('button',{name:'资源仪表',exact:true}).click();
  if(!await page.locator('#meters').isVisible())throw Error('资源仪表不可见');
  if(await page.locator('#meters .bar').count()!==3)throw Error('原有资源条被替换');
  await page.getByRole('button',{name:'能源分配',exact:true}).click();
  if(!await page.locator('#power').isVisible())throw Error('能源分配不可见');
  if(!await page.locator('.allocation-scroll').evaluate(el=>{const last=el.querySelector('.slot:last-child').getBoundingClientRect();const box=el.getBoundingClientRect();return last.bottom<=box.bottom+1;}))throw Error('分电面板只显示部分设备');
  const initial=await page.evaluate(()=>__dbg.G().alloc.o2);
  await page.locator('.slot[data-k="o2"] .pl').click();
  if(await page.evaluate(()=>__dbg.G().alloc.o2)!==initial+1)throw Error('分电按钮失效');
  await page.getByRole('button',{name:'3D 基地全景',exact:true}).click();
  const before=await page.evaluate(()=>({o2:__dbg.G().o2,dose:__dbg.G().dose,batt:__dbg.G().batt}));
  if(!await page.locator('#habitatScene').isHidden() || await page.evaluate(()=>Expedition.outside || World.getPlayer().active))throw Error('全景与实际出舱混淆');
  if(await page.locator('#viewOverview').getAttribute('aria-pressed')!=='true')throw Error('全景状态不正确');
  await page.getByRole('button',{name:'资源仪表',exact:true}).click();
  await page.screenshot({path:'output/playwright/restored-resource-instruments.png'});
  await page.getByRole('button',{name:'能源分配',exact:true}).click();
  await page.screenshot({path:'output/playwright/restored-energy-allocation.png'});
  await page.getByRole('button',{name:'关闭手册',exact:true}).click();
  await page.waitForTimeout(2500);
  await page.screenshot({path:'output/playwright/restored-base-panorama.png'});
  const after=await page.evaluate(()=>({o2:__dbg.G().o2,dose:__dbg.G().dose,batt:__dbg.G().batt}));
  if(JSON.stringify(before)!==JSON.stringify(after))throw Error('查看全景消耗物资');
  await page.getByRole('button',{name:'基地生活',exact:true}).click();
  if(!await page.locator('#habitatScene').isVisible())throw Error('无法返回生活舱');
  await page.getByRole('button',{name:'出舱探索',exact:true}).click();
  await page.locator('#fieldDialog').getByRole('button',{name:'出舱',exact:true}).click();
  if(!await page.evaluate(()=>Expedition.outside && World.getPlayer().active))throw Error('第三人称操控失效');
  if(await page.evaluate(()=>__dbg.G().o2)!==before.o2-3)throw Error('实际出舱未扣氧气');
  return {resources:'original meters',allocation:'working',panorama:'no resource cost',EVA:'third person'};
}
